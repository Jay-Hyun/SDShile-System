#!/usr/bin/env python3
"""Everything the overlay needs, in draft seconds, as assets/js/subs.js (window.SUBS).

lyrics   the 33 display lines (data/lyrics.json, Korean + English) timed word by word. The draft's song is the earlier
         3-minute edit (wedding-video) shifted by OFFSET (measured by cross-correlation, constant to 1 ms), so word
         times come from that edit's forced alignment (wedding-video/data/edit_lyrics.json) + OFFSET.
         Each line also gets a zone for its large background words: away from faces (YuNet on frames across the
         line), in the black side bars when the shot is a pillarboxed vertical picture.
msgs     the friends' messages (data/messages.timed.json, forced-aligned) as boxed captions.
reels    the vertical video spans (work/layout.json) that get the Reels UI.
"""
import json
import subprocess

import cv2
import numpy as np

OFFSET = 3.413
DUR = 229.333
W, H = 1920, 1080

lines = json.load(open("data/lyrics.json"))
old = [w for e in json.load(open("../wedding-video/data/edit_lyrics.json")) for w in e["words"]]
i = 0
for l in lines:
    l["words"] = []
    for t in l["ko"].split():
        while old[i]["t"] != t:
            i += 1
        l["words"].append({"t": t, "s": round(old[i]["start"] + OFFSET, 3), "e": round(old[i]["end"] + OFFSET, 3)})
        i += 1
for k, l in enumerate(lines):
    l["s"] = l["words"][0]["s"] - 0.12
    nxt = lines[k + 1]["words"][0]["s"] - 0.12 if k + 1 < len(lines) else DUR
    l["e"] = round(min(nxt, l["words"][-1]["e"] + 1.2), 3)
    l["s"] = round(l["s"], 3)

layout = json.load(open("work/layout.json"))


def layout_at(t):
    for s in layout:
        if s["t0"] <= t < s["t1"]:
            return s
    return layout[-1]


det = cv2.FaceDetectorYN.create("work/models/yunet.onnx", "", (640, 360), 0.6)


def frame(t):
    raw = subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-ss", f"{t:.3f}", "-i", "assets/raw/draft.mov",
                          "-frames:v", "1", "-vf", "scale=640:360", "-f", "rawvideo", "-pix_fmt", "bgr24", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(360, 640, 3)


def faces(t):
    _, f = det.detect(frame(t))
    out = []
    for r in (f if f is not None else []):
        x, y, w, h = (r[:4] * 3).tolist()
        out.append((x - 0.35 * w, y - 0.5 * h, x + 1.35 * w, y + 1.6 * h))  # head plus hair and a margin
    return out


ZONES = {"UL": (100, 70, 900, 420), "UR": (1020, 70, 1820, 420), "ML": (100, 360, 900, 700), "MR": (1020, 360, 1820, 700)}


def overlap(a, b):
    return max(0, min(a[2], b[2]) - max(a[0], b[0])) * max(0, min(a[3], b[3]) - max(a[1], b[1]))


prev = None
for l in lines:
    ts = np.linspace(l["s"] + 0.1, l["e"] - 0.1, 4)
    lay = layout_at((l["s"] + l["e"]) / 2)
    fs = [b for t in ts for b in faces(t)]
    if lay["kind"] == "pillar" and lay["x0"] >= 380:
        bar = lay["x0"]  # black bar width each side
        cand = {"BL": (40, 120, bar - 40, 760), "BR": (W - bar + 40, 120, W - 40, 760)}
    else:
        cand = ZONES
    score = {z: sum(overlap(r, f) for f in fs) / 1e4 + (0.5 if z == prev else 0) + (0.2 if z.startswith("M") else 0)
             for z, r in cand.items()}
    z = min(score, key=score.get)
    l["zone"], l["box"] = z, cand[z]
    prev = z
    print(f'{l["s"]:7.2f}-{l["e"]:7.2f} {z} faces={len(fs)} {l["ko"]}')

M = json.load(open("data/messages.timed.json"))
msgs = []
for key, sec in M.items():
    ls = sec["lines"]
    for k, l in enumerate(ls):
        s = l["start"] - 0.15
        nxt = ls[k + 1]["start"] - 0.15 if k + 1 < len(ls) else sec["t1"]
        e = min(nxt, l["end"] + 1.0)
        msgs.append({"sec": key, "who": l.get("who", sec["name"]), "ko": l["ko"], "group": bool(l.get("group")),
                     "s": round(s, 3), "e": round(e, 3)})
reels = [{"s": s["t0"], "e": s["t1"], "x0": s["x0"], "w": s["w"]} for s in layout
         if s["kind"] == "pillar" and s["w"] < 900 and s["mot"] > 1.0 and s["t1"] - s["t0"] > 3]

SUBS = {"dur": DUR, "lyrics": lines, "msgs": msgs, "reels": reels, "outro": {"s": 224.3, "e": DUR}}
with open("assets/js/subs.js", "w") as f:
    f.write("/* generated by scripts/build_subs.py — do not edit */\nwindow.SUBS = ")
    json.dump(SUBS, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print("reels:", reels)
